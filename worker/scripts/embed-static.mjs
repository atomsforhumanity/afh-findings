// Embed ../static/bar.js (shared with the Python preview) into the Worker as a string.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const bar = readFileSync(join(here, "..", "..", "static", "bar.js"), "utf8");
const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "static.ts"),
  `// Generated by scripts/embed-static.mjs from static/bar.js. Do not edit.\nexport const BAR_JS = ${JSON.stringify(bar)};\n`,
);
