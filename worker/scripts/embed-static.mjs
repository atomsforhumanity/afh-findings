// Embed ../static (shared with the Python preview) into the Worker: bar.js, fonts.css, and the
// font files with their licenses, served under /_static/.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const staticDir = join(here, "..", "..", "static");
const types = { ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".woff2": "font/woff2", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml" };

const files = {};
function add(rel) {
  const ext = rel.slice(rel.lastIndexOf("."));
  const type = types[ext];
  if (!type) return;
  const data = readFileSync(join(staticDir, rel));
  files[rel] = ext === ".woff2" ? { type, base64: data.toString("base64") } : { type, text: data.toString("utf8") };
}
for (const name of readdirSync(staticDir)) if (name.includes(".")) add(name);
for (const name of readdirSync(join(staticDir, "fonts"))) add(`fonts/${name}`);

const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });
const target = join(out, "static.ts");
const content =
  "// Generated by scripts/embed-static.mjs from ../static. Do not edit.\n" +
  "export const STATIC_FILES: Record<string, { type: string; text?: string; base64?: string }> = " +
  `${JSON.stringify(files)};\n`;
// Write only on change: wrangler dev watches src/, and a rewrite would trigger another build.
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {}
if (current !== content) writeFileSync(target, content);
